"""
OpenAI-compatible LLM Provider for NYAYASETU.
Uses standard HTTP POST to /chat/completions (compatible with OpenAI, Groq, Ollama, vLLM).
"""
import json
import logging
import urllib.request
import urllib.error
from apps.assistant.llm.base import BaseLLMProvider

logger = logging.getLogger(__name__)


class OpenAILLMProvider(BaseLLMProvider):
    def __init__(self, api_key: str, model_name: str = "gpt-4o-mini", base_url: str = "https://api.openai.com/v1"):
        self.api_key = api_key
        self.model_name = model_name or "gpt-4o-mini"
        self.base_url = (base_url or "https://api.openai.com/v1").rstrip("/")

    def generate(self, system_prompt: str, user_prompt: str) -> str:
        if not self.api_key:
            raise ValueError("OPENAI_API_KEY / LLM_API_KEY is not configured.")

        url = f"{self.base_url}/chat/completions"
        payload = {
            "model": self.model_name,
            "messages": [
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt}
            ],
            "temperature": 0.1,
            "max_tokens": 1024,
        }

        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data,
            headers={
                "Content-Type": "application/json",
                "Authorization": f"Bearer {self.api_key}"
            }
        )

        try:
            with urllib.request.urlopen(req, timeout=30) as response:
                res_data = json.loads(response.read().decode("utf-8"))
                choices = res_data.get("choices", [])
                if choices:
                    return choices[0].get("message", {}).get("content", "").strip()
                return "No response generated by provider."
        except urllib.error.HTTPError as e:
            error_body = e.read().decode("utf-8")
            logger.error("LLM API error (%d): %s", e.code, error_body)
            raise RuntimeError(f"LLM API error: {e.code} - {error_body}")
        except Exception as exc:
            logger.exception("Failed to connect to LLM API: %s", exc)
            raise RuntimeError(f"Failed to communicate with LLM: {exc}")

