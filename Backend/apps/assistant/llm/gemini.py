"""
Google Gemini LLM Provider for NYAYASETU.
Uses Gemini REST API or google-generativeai library when an API key is present.
"""
import json
import logging
import urllib.request
import urllib.error
from apps.assistant.llm.base import BaseLLMProvider

logger = logging.getLogger(__name__)


class GeminiLLMProvider(BaseLLMProvider):
    def __init__(self, api_key: str, model_name: str = "gemini-1.5-flash"):
        self.api_key = api_key
        self.model_name = model_name or "gemini-1.5-flash"

    def generate(self, system_prompt: str, user_prompt: str) -> str:
        if not self.api_key:
            raise ValueError("GEMINI_API_KEY / LLM_API_KEY is not configured.")

        # REST API endpoint
        url = (
            f"https://generativelanguage.googleapis.com/v1beta/models/"
            f"{self.model_name}:generateContent?key={self.api_key}"
        )

        payload = {
            "system_instruction": {
                "parts": [{"text": system_prompt}]
            },
            "contents": [
                {
                    "role": "user",
                    "parts": [{"text": user_prompt}]
                }
            ],
            "generationConfig": {
                "temperature": 0.1,  # Low temperature for factuality
                "topP": 0.95,
                "maxOutputTokens": 1024,
            }
        }

        data = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data,
            headers={"Content-Type": "application/json"}
        )

        try:
            with urllib.request.urlopen(req, timeout=30) as response:
                res_data = json.loads(response.read().decode("utf-8"))
                candidates = res_data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts:
                        return parts[0].get("text", "").strip()
                return "No response generated by Gemini."
        except urllib.error.HTTPError as e:
            error_body = e.read().decode("utf-8")
            logger.error("Gemini API error (%d): %s", e.code, error_body)
            raise RuntimeError(f"Gemini API error: {e.code} - {error_body}")
        except Exception as exc:
            logger.exception("Failed to connect to Gemini API: %s", exc)
            raise RuntimeError(f"Failed to communicate with Gemini LLM: {exc}")

